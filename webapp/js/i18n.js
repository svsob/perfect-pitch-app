export function makeT(lang) {
  const table = T[lang] || T.en;
  return (key, vars = {}) => (table[key] ?? T.en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

export function noteName(_lang, n) {
  return SOLFEGE[n];
}
